#!/usr/bin/env python3
"""Render the runtime directory of the Host D test instance from a repo copy.

usage: render.py <repo copy> <runtime dir> [--init --backend-image IMG --frontend-image IMG]

Every run (idempotent, safe to repeat after a repo update):
  - base.env           <- data of the renfield-env ConfigMap in k8s/configmap.yaml, so the
                          test instance follows the production settings
  - searxng/settings.yml <- the searxng-settings ConfigMap in k8s/searxng.yaml
  - config/mcp_servers.yaml, agent_roles.yaml <- config/ (ConfigMap-served in prod too)
  - config/mail_accounts.yaml <- config/mail_accounts.default.yaml
  - docker-compose.yml, Caddyfile, overrides.env <- deploy/hostd/renfield-test/
  config/kg_scopes.yaml is NOT in the repo (it lives only in the prod ConfigMap); it must be
  placed once by hand (README.md) — the run refuses to finish without it.

--init (first install only; refuses to overwrite):
  - secrets.env with fresh random values (never printed)
  - .env with the image refs (later written by bin/update-compose-instance.sh)
"""
import argparse
import os
import secrets
import shutil
import sys

import yaml


def configmap(path, name):
    with open(path) as f:
        docs = list(yaml.safe_load_all(f))
    for doc in docs:
        if doc and doc.get("kind") == "ConfigMap" and doc["metadata"]["name"] == name:
            return doc["data"]
    sys.exit(f"ConfigMap {name} not found in {path}")


def write(path, text, mode=0o644):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.chmod(tmp, mode)
    os.replace(tmp, path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("repo")
    ap.add_argument("run")
    ap.add_argument("--init", action="store_true")
    ap.add_argument("--backend-image")
    ap.add_argument("--frontend-image")
    a = ap.parse_args()
    src = os.path.join(a.repo, "deploy/hostd/renfield-test")

    env = configmap(os.path.join(a.repo, "k8s/configmap.yaml"), "renfield-env")
    lines = []
    for k, v in env.items():
        v = "" if v is None else str(v)
        if "\n" in v or "$" in v:
            sys.exit(f"{k}: newline or '$' in the value, an env_file cannot carry it unchanged")
        lines.append(f"{k}={v}")
    write(os.path.join(a.run, "base.env"),
          "# GENERATED by render.py from k8s/configmap.yaml — do not edit, see overrides.env\n"
          + "\n".join(lines) + "\n")

    sx = configmap(os.path.join(a.repo, "k8s/searxng.yaml"), "searxng-settings")["settings.yml"]
    write(os.path.join(a.run, "searxng/settings.yml"), sx)

    for name in ("mcp_servers.yaml", "agent_roles.yaml"):
        shutil.copyfile(os.path.join(a.repo, "config", name), os.path.join(a.run, "config", name))
    shutil.copyfile(os.path.join(a.repo, "config/mail_accounts.default.yaml"),
                    os.path.join(a.run, "config/mail_accounts.yaml"))
    for name in ("docker-compose.yml", "Caddyfile", "overrides.env"):
        shutil.copyfile(os.path.join(src, name), os.path.join(a.run, name))

    if a.init:
        for name in ("secrets.env", ".env"):
            if os.path.exists(os.path.join(a.run, name)):
                sys.exit(f"--init: {name} exists already, refusing to overwrite it")
        if not (a.backend_image and a.frontend_image):
            sys.exit("--init needs --backend-image and --frontend-image")
        pg, rd = secrets.token_hex(24), secrets.token_hex(24)
        write(os.path.join(a.run, "secrets.env"), "\n".join([
            "# GENERATED once by render.py --init. Never commit, never print.",
            f"SECRET_KEY={secrets.token_urlsafe(48)}",
            f"POSTGRES_PASSWORD={pg}",
            f"DATABASE_URL=postgresql+asyncpg://renfield:{pg}@postgres:5432/renfield",
            f"REDIS_PASSWORD={rd}",
            f"REDIS_URL=redis://:{rd}@redis:6379/0",
            # The rate limiter has its own Redis URL (k8s: the redis-auth Secret sets both);
            # without the password every request fails with a 500 from the limiter.
            f"API_RATE_LIMIT_STORAGE_URI=redis://:{rd}@redis:6379/0",
            f"DEFAULT_ADMIN_PASSWORD={secrets.token_urlsafe(18)}",
            f"PAPERLESS_SECRET_KEY={secrets.token_urlsafe(48)}",
            f"PAPERLESS_ADMIN_PASSWORD={secrets.token_urlsafe(18)}",
            f"PAPERLESS_REDIS=redis://:{rd}@redis:6379/5",
            "# filled in by README.md step 4 once Paperless is up",
            "PAPERLESS_API_TOKEN=",
        ]) + "\n", mode=0o600)
        write(os.path.join(a.run, ".env"),
              f"RENFIELD_BACKEND_IMAGE={a.backend_image}\nRENFIELD_FRONTEND_IMAGE={a.frontend_image}\n")

    missing = [n for n in ("config/kg_scopes.yaml", "secrets.env", ".env")
               if not os.path.exists(os.path.join(a.run, n))]
    if missing:
        sys.exit("rendered, but still missing: " + ", ".join(missing) + " (README.md)")
    print("rendered", a.run, f"({len(lines)} base keys)")


if __name__ == "__main__":
    main()
